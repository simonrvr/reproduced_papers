def _run_record(run_dir: Path) -> dict:
    status = json.loads((run_dir / "run_status.json").read_text(encoding="utf-8"))
    config = json.loads((run_dir / "config_snapshot.json").read_text(encoding="utf-8"))
    if status["status"] != "COMPLETED":
        raise RuntimeError(f"{run_dir} is {status['status']}, not COMPLETED")
    return {
        "run": str(run_dir.relative_to(PAPER_DIR)),
        "description": config.get("description", ""),
        "seed": status["seed"],
        "commit": status["code"]["commit"][:12],
        "dirty": status["code"]["dirty"],
        "started_at": status["started_at"],
        "completed_at": status["completed_at"],
    }


def main() -> int:
    """Copy the tables, build the per-seed training table, write provenance."""
    RESULTS.mkdir(exist_ok=True)
    lines = [
        "# Provenance of curated result tables",
        "",
        "Generated by `utils/curate_results.py` from completed runs in `outdir/`.",
        "Hardware: Apple M2 CPU; Python 3.13.15; merlinquantum 0.4.1;",
        "perceval-quandela 1.2.4; torch 2.14.1. `dirty = True` means the paper",
        "folder was uncommitted when the run started.",
        "",
        "| File | Source run | Seed | Commit | Dirty | Started (UTC) | Completed (UTC) | Configuration |",
        "|---|---|---:|---|---|---|---|---|",
    ]
    for name, source, filename in TABLES:
        run_dir = OUTDIR / source
        record = _run_record(run_dir)
        shutil.copyfile(run_dir / filename, RESULTS / name)
        lines.append(
            f"| `{name}` | `{record['run']}/{filename}` | {record['seed']} | `{record['commit']}` | "
            f"{record['dirty']} | {record['started_at']} | {record['completed_at']} | "
            f"{record['description'][:160]} |"
        )
    seed_rows = []
    for label, source in TRAINING_RUNS:
        run_dir = OUTDIR / source
        record = _run_record(run_dir)
        metrics = json.loads((run_dir / "metrics.json").read_text(encoding="utf-8"))
        for result in metrics["results"]:
            seed_rows.append({"run": label, **result})
        lines.append(
            f"| `training_runs_per_seed.csv` ({label}) | `{record['run']}/metrics.json` | "
            f"{record['seed']} | `{record['commit']}` | {record['dirty']} | "
            f"{record['started_at']} | {record['completed_at']} | {record['description'][:160]} |"
        )
    with (RESULTS / "training_runs_per_seed.csv").open(
        "w", newline="", encoding="utf-8"
    ) as handle:
        writer = csv.DictWriter(handle, fieldnames=list(seed_rows[0]))
        writer.writeheader()
        writer.writerows(seed_rows)
    (RESULTS / "PROVENANCE.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"copied {len(TABLES)} tables and {len(seed_rows)} training rows")
    return 0


if __name__ == "__main__":
    sys.exit(main())
