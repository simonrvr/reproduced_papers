"""Coordinated learning-rate selection sweep for one training config.

Usage (from the repository root)::

    python3 papers/photonic_trainability/utils/run_lr_sweep.py \\
        --config configs/fig7_nn_training_reduced.json --sweep-id lrsel_fig7_m8

For each candidate in the config's ``learning_rate_grid`` the coordinator writes a
candidate config (``gpsr_exact`` on ``selection_seed`` only, fixed
``learning_rate``, plus ``sweep_id`` / ``candidate`` / ``repetition``) and runs it
through the shared runtime as its own run, one candidate after another. The
coordinator alone writes ``sweep.log`` and ``sweep_status.json`` in
``papers/photonic_trainability/outdir/sweeps/<sweep_id>/``; each candidate keeps
its own ``run.log``, ``run_status.json``, ``config_snapshot.json`` and
``metrics.json``.

Selection rule (predeclared in LOG.md): lowest finite final exact loss on the
selection seed; ties within 1e-12 go to the smaller rate. The summary table
``summary.csv`` is generated from the candidates' ``metrics.json`` files.
"""

from __future__ import annotations

import argparse
import csv
import json
import logging
import math
import subprocess
import sys
from pathlib import Path

PROJECT_DIR = Path(__file__).resolve().parents[1]
REPO_ROOT = PROJECT_DIR.parents[1]
sys.path.insert(0, str(PROJECT_DIR.parent))

from photonic_trainability.lib.experiment_logging import (  # noqa: E402
    configure_logging,
    git_state,
    sweep_progress,
    utc_now,
    write_json,
)

logger = logging.getLogger("lr_sweep")
TIE_TOLERANCE = 1e-12


def _rel(path: Path, base: Path) -> str:
    return str(Path(path).resolve().relative_to(base.resolve(), walk_up=True))


def main(argv: list[str] | None = None) -> int:
    """Run the sweep; exit status 0 only for a complete sweep."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--config", required=True, help="Path relative to the paper folder"
    )
    parser.add_argument("--sweep-id", required=True)
    args = parser.parse_args(argv)

    base = json.loads((PROJECT_DIR / args.config).read_text(encoding="utf-8"))
    candidates = [float(value) for value in base["learning_rate_grid"]]
    sweep_dir = PROJECT_DIR / "outdir" / "sweeps" / args.sweep_id
    sweep_dir.mkdir(parents=True, exist_ok=False)
    configure_logging(sweep_dir / "sweep.log")

    status = {
        "schema_version": 1,
        "sweep_id": args.sweep_id,
        "status": "RUNNING",
        "started_at": utc_now(),
        "completed_at": None,
        "code": git_state(PROJECT_DIR),
        "expected_runs": len(candidates),
        "runs": [
            {
                "run_id": None,
                "candidate": {"learning_rate": rate},
                "seed": int(base["selection_seed"]),
                "repetition": 0,
                "status": "PLANNED",
                "run_dir": None,
                "run_log": None,
                "run_status": None,
                "config_path": None,
                "metrics_path": None,
            }
            for rate in candidates
        ],
        "summary_path": None,
        "selected_candidates": [],
        "error": None,
    }
    status_path = sweep_dir / "sweep_status.json"
    write_json(status_path, status)
    logger.info(
        "SWEEP_STARTED | sweep_id=%s | expected_runs=%d | base_config=%s",
        args.sweep_id,
        len(candidates),
        args.config,
    )
    for entry in status["runs"]:
        rate = entry["candidate"]["learning_rate"]
        candidate_cfg = {
            key: value
            for key, value in base.items()
            if key not in ("learning_rate_grid", "selection_seed")
        }
        candidate_cfg.update(
            description=f"{args.sweep_id} candidate learning_rate={rate:g} (gpsr_exact on "
            f"selection seed {entry['seed']}); generated by utils/run_lr_sweep.py",
            seed=entry["seed"],
            methods=["gpsr_exact"],
            seeds=[entry["seed"]],
            learning_rate=rate,
            sweep_id=args.sweep_id,
            candidate={"learning_rate": rate},
            repetition=0,
            selection={
                "name": "final exact loss of gpsr_exact on the selection seed",
                "direction": "minimize",
                "split": f"selection_seed={entry['seed']}",
                "checkpoint": "last_iteration",
            },
        )
        candidate_dir = sweep_dir / f"lr_{rate:g}"
        candidate_dir.mkdir()
        config_file = candidate_dir / "candidate_config.json"
        config_file.write_text(
            json.dumps(candidate_cfg, indent=2) + "\n", encoding="utf-8"
        )
        entry["status"] = "RUNNING"
        write_json(status_path, status)
        logger.info(
            "CANDIDATE_STARTED | candidate=lr=%g | config=%s",
            rate,
            _rel(config_file, sweep_dir),
        )
        logger.info("SWEEP_PROGRESS | %s", sweep_progress(status))
        command = [
            sys.executable,
            str(REPO_ROOT / "implementation.py"),
            "--paper",
            "photonic_trainability",
            "--config",
            str(config_file),
            "--outdir",
            str(candidate_dir),
        ]
        result = subprocess.run(command, cwd=REPO_ROOT, capture_output=True, text=True)
        run_dirs = sorted(candidate_dir.glob("run_*"))
        run_dir = run_dirs[-1] if run_dirs else None
        run_status = (
            json.loads((run_dir / "run_status.json").read_text(encoding="utf-8"))
            if run_dir is not None and (run_dir / "run_status.json").exists()
            else None
        )
        if (
            result.returncode == 0
            and run_status
            and run_status["status"] == "COMPLETED"
        ):
            entry.update(
                run_id=run_status["run_id"],
                status="COMPLETED",
                run_dir=_rel(run_dir, sweep_dir),
                run_log=_rel(run_dir / "run.log", sweep_dir),
                run_status=_rel(run_dir / "run_status.json", sweep_dir),
                config_path=_rel(run_dir / "config_snapshot.json", sweep_dir),
                metrics_path=_rel(run_dir / "metrics.json", sweep_dir),
            )
            write_json(status_path, status)
            logger.info(
                "CANDIDATE_COMPLETED | run_id=%s | metrics=%s",
                entry["run_id"],
                entry["metrics_path"],
            )
        else:
            entry["status"] = "FAILED"
            if run_status:
                entry.update(
                    run_id=run_status["run_id"], run_dir=_rel(run_dir, sweep_dir)
                )
            write_json(status_path, status)
            logger.info(
                "CANDIDATE_FAILED | candidate=lr=%g | returncode=%d | stderr_tail=%s",
                rate,
                result.returncode,
                result.stderr[-500:],
            )
        logger.info("SWEEP_PROGRESS | %s", sweep_progress(status))

    rows = []
    for entry in status["runs"]:
        if entry["status"] != "COMPLETED":
            continue
        metrics = json.loads(
            (sweep_dir / entry["metrics_path"]).read_text(encoding="utf-8")
        )
        rows.append(
            {
                "learning_rate": entry["candidate"]["learning_rate"],
                "seed": entry["seed"],
                "final_exact_loss": metrics["results"][0]["final_exact_loss"],
                "run_id": entry["run_id"],
                "metrics_path": entry["metrics_path"],
            }
        )
    finite = [row for row in rows if math.isfinite(row["final_exact_loss"])]
    selected = []
    if finite:
        best = min(row["final_exact_loss"] for row in finite)
        tied = [
            row for row in finite if row["final_exact_loss"] - best <= TIE_TOLERANCE
        ]
        selected = [{"learning_rate": min(row["learning_rate"] for row in tied)}]
    for row in rows:
        row["selected"] = (
            bool(selected) and row["learning_rate"] == selected[0]["learning_rate"]
        )
    summary_path = sweep_dir / "summary.csv"
    if rows:
        with summary_path.open("w", newline="", encoding="utf-8") as handle:
            writer = csv.DictWriter(handle, fieldnames=list(rows[0]))
            writer.writeheader()
            writer.writerows(rows)
        status["summary_path"] = _rel(summary_path, sweep_dir)
    complete = len(finite) == len(candidates) and all(
        entry["status"] == "COMPLETED" for entry in status["runs"]
    )
    status.update(
        status="COMPLETED" if complete else ("PARTIAL" if rows else "FAILED"),
        completed_at=utc_now(),
        selected_candidates=selected if complete else [],
    )
    if not rows:
        status["error"] = {
            "type": "NoCompletedCandidates",
            "message": "every candidate failed",
        }
    write_json(status_path, status)
    event = {
        "COMPLETED": "SWEEP_COMPLETED",
        "PARTIAL": "SWEEP_PARTIAL",
        "FAILED": "SWEEP_FAILED",
    }[status["status"]]
    logger.info(
        "%s | summary=%s | selected=%s",
        event,
        status["summary_path"],
        status["selected_candidates"],
    )
    return 0 if complete else 1


if __name__ == "__main__":
    sys.exit(main())
